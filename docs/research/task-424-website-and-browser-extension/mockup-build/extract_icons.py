"""Extract Ionicons glyph outlines from the font the mobile app ships, as SVG symbols.

Run from the repository root:
    python3 docs/research/task-424-website-and-browser-extension/mockup-build/extract_icons.py
Writes icons.js next to this script. Same method as the task-408/410/424 mockups:
the glyph is the exact outline of @expo/vector-icons' Ionicons.ttf, no network.
"""
import json
import pathlib

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = pathlib.Path.cwd()
VENDOR = ROOT / "mobile/node_modules/@expo/vector-icons/build/vendor/react-native-vector-icons"
NAMES = """search-outline folder-outline folder-open-outline folder chevron-forward chevron-down
chevron-back add close ellipsis-horizontal file-tray-outline newspaper-outline person-outline
sparkles-outline sparkles book-outline send stop arrow-up time-outline chatbubbles-outline
chatbubble-ellipses-outline refresh alert-circle-outline checkmark checkmark-circle link-outline
document-text-outline image-outline cloud-upload-outline trash-outline create-outline
swap-horizontal-outline moon-outline sunny-outline language-outline log-out-outline bug-outline
bulb-outline open-outline play-circle-outline headset-outline videocam-outline mic-outline
camera-outline layers-outline albums-outline star-outline star pin-outline pin home-outline
return-down-forward-outline list-outline grid-outline filter-outline arrow-forward
reorder-three-outline copy-outline git-branch-outline menu-outline calendar-outline today-outline
school-outline help-circle-outline text-outline globe-outline card-outline extension-puzzle-outline
keypad-outline return-up-back-outline pulse sync wifi-outline options-outline documents-outline
library-outline camera contrast-outline folder-open images-outline document-attach-outline arrow-back
checkmark-circle-outline shield-checkmark information-circle-outline""".split()

glyphmap = json.loads((VENDOR / "glyphmaps/Ionicons.json").read_text())
font = TTFont(str(VENDOR / "Fonts/Ionicons.ttf"))
cmap = font.getBestCmap()
glyphs = font.getGlyphSet()
upm = font["head"].unitsPerEm
# The icon em box runs from the typo descender (-64) to the typo ascender (448).
ascent = font["OS/2"].sTypoAscender
symbols = []
for name in NAMES:
    gname = cmap[glyphmap[name]]
    pen = SVGPathPen(glyphs)
    # Font space is y-up; SVG is y-down. Flip around the ascent line.
    glyphs[gname].draw(TransformPen(pen, (1, 0, 0, -1, 0, ascent)))
    symbols.append(f'<symbol id="i-{name}" viewBox="0 0 {upm} {upm}"><path d="{pen.getCommands()}"/></symbol>')
out = pathlib.Path(__file__).with_name("icons.js")
out.write_text("// Generated by extract_icons.py from Ionicons.ttf — do not edit.\nconst ICON_SPRITE = `<svg xmlns=\"http://www.w3.org/2000/svg\" style=\"display:none\">" + "".join(symbols) + "</svg>`;\n")
print(len(symbols), "symbols,", out.stat().st_size, "bytes, upm", upm, "ascent", ascent)
