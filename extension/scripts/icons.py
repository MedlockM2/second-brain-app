"""Writes lib/icons.generated.ts: the Ionicons outlines the extension draws.

They are read from the web app's own extraction (web/src/components/icons.generated.ts),
so the side panel draws the same glyphs as the app without importing from web/.
Rerun after adding a name to ICONS: python3 scripts/icons.py
"""

import json
import re
from pathlib import Path

ICONS = [
    "add", "alert-circle-outline", "arrow-forward", "arrow-up", "book-outline", "checkmark", "checkmark-circle",
    "chevron-back", "chevron-down", "close", "close-circle", "copy-outline", "create-outline", "document-text-outline",
    "ellipsis-horizontal", "eye-outline", "folder-outline", "globe-outline", "headset-outline", "help-circle-outline",
    "images-outline", "language-outline", "lock-closed-outline", "log-out-outline", "newspaper", "open-outline",
    "play-circle-outline", "refresh-outline", "search-outline", "sparkles", "sparkles-outline", "sync-outline",
    "time-outline",
]

root = Path(__file__).resolve().parents[2]
source = (root / "web" / "src" / "components" / "icons.generated.ts").read_text()
paths = dict(re.findall(r'^\s*"([a-z-]+)":\s*"([^"]+)"', source, re.MULTILINE))
missing = [name for name in ICONS if name not in paths]
if missing:
    raise SystemExit(f"Not in the web extraction: {missing} (add them to web/scripts/extract_icons.py first)")
body = ",\n".join(f"  {json.dumps(name)}: {json.dumps(paths[name])}" for name in ICONS)
out = Path(__file__).resolve().parent.parent / "lib" / "icons.generated.ts"
out.write_text(
    "// Generated by extension/scripts/icons.py from web/src/components/icons.generated.ts — do not edit.\n"
    f"export const ICON_PATHS = {{\n{body},\n}} as const;\n"
)
print(len(ICONS), "icons")
