for key, by_locale in EXTENSION_MESSAGES.items():
    KEYS.append(key)
    for locale, values in T.items():
        values.append(by_locale[locale])

root = Path(__file__).resolve().parent.parent / "public" / "_locales"
for lang, values in T.items():
    assert len(values) == len(KEYS), lang
    # The stores cut a longer description.
    assert len(values[KEYS.index("extDescription")]) <= 132, lang
    folder = root / lang
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "messages.json").write_text(
        json.dumps({k: {"message": v} for k, v in zip(KEYS, values)}, ensure_ascii=False, indent=2) + "\n"
    )
print(len(T), "locales,", len(KEYS), "messages")
