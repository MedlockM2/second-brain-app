"""Write web/src/components/icons.generated.ts: the Ionicons the web app draws, as path data.

Run from the repository root after adding a name to NAMES:
    python3 web/scripts/extract_icons.py
The outlines are those of the Ionicons font the mobile app ships (@expo/vector-icons,
hoisted to the root node_modules by the workspace install), so a glyph is the same on
both apps and no icon package or network is needed. Needs fontTools (pip install fonttools).
"""
import json
import pathlib

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

NAMES = sorted(set("""
add alert-circle-outline chevron-back chevron-down chevron-forward document-attach-outline
document-text-outline file-tray-outline folder headset-outline images-outline layers-outline
link-outline log-out-outline moon-outline musical-notes-outline person-outline play-circle-outline
search-outline share-outline sparkles sunny-outline text-outline globe-outline bug-outline
bulb-outline extension-puzzle-outline card-outline
book-outline card-outline checkmark checkmark-circle chatbubbles-outline close ellipsis-horizontal
folder-outline add-circle-outline pencil-outline trash-outline sync-outline open-outline language-outline
bulb-outline help-circle-outline close-circle refresh-outline sparkles-outline arrow-forward
information-circle-outline eye-outline eye-off-outline time-outline cloud-upload-outline
create-outline arrow-up arrow-down stop download newspaper remove-circle-outline
play school-outline desktop-outline mail-open-outline
person-circle-outline logo-apple logo-google ellipse-outline
""".split()))

ROOT = pathlib.Path.cwd()
VENDOR = ROOT / "node_modules/@expo/vector-icons/build/vendor/react-native-vector-icons"
OUT = ROOT / "web/src/components/icons.generated.ts"

glyphmap = json.loads((VENDOR / "glyphmaps/Ionicons.json").read_text())
font = TTFont(str(VENDOR / "Fonts/Ionicons.ttf"))
cmap = font.getBestCmap()
glyphs = font.getGlyphSet()
upm = font["head"].unitsPerEm
# The icon em box runs from the typo descender to the typo ascender; font space is
# y-up and SVG y-down, so the outline is flipped around the ascent line.
ascent = font["OS/2"].sTypoAscender

lines = [
    "// Generated by web/scripts/extract_icons.py from the Ionicons font — do not edit.",
    f'export const ICON_VIEWBOX = "0 0 {upm} {upm}";',
    "",
    "export const ICON_PATHS = {",
]
for name in NAMES:
    pen = SVGPathPen(glyphs)
    glyphs[cmap[glyphmap[name]]].draw(TransformPen(pen, (1, 0, 0, -1, 0, ascent)))
    lines.append(f'  "{name}": "{pen.getCommands()}",')
lines += ["} as const;", ""]
OUT.write_text("\n".join(lines))
print(len(NAMES), "icons ->", OUT.relative_to(ROOT))
